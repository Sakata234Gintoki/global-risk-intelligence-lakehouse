-- Run once as ACCOUNTADMIN. Replace <ACCOUNT_ID>, <AWS_ROLE> and <BUCKET>/<PREFIX>.

CREATE DATABASE IF NOT EXISTS GRIL;
CREATE SCHEMA   IF NOT EXISTS GRIL.RAW;
CREATE SCHEMA   IF NOT EXISTS GRIL.STAGING;
CREATE SCHEMA   IF NOT EXISTS GRIL.SNAPSHOTS;
CREATE SCHEMA   IF NOT EXISTS GRIL.MARTS;

CREATE WAREHOUSE IF NOT EXISTS GRIL_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE ROLE IF NOT EXISTS GRIL_TRANSFORMER;
GRANT USAGE, OPERATE ON WAREHOUSE GRIL_WH TO ROLE GRIL_TRANSFORMER;
GRANT ALL ON DATABASE GRIL TO ROLE GRIL_TRANSFORMER;
GRANT ALL ON ALL SCHEMAS IN DATABASE GRIL TO ROLE GRIL_TRANSFORMER;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE GRIL TO ROLE GRIL_TRANSFORMER;
GRANT ALL ON FUTURE TABLES  IN DATABASE GRIL TO ROLE GRIL_TRANSFORMER;
-- GRANT ROLE GRIL_TRANSFORMER TO USER <your_user>;

-- S3 access (then run DESC INTEGRATION GRIL_S3_INT and add the IAM trust relationship in AWS)
CREATE STORAGE INTEGRATION IF NOT EXISTS GRIL_S3_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::<ACCOUNT_ID>:role/<AWS_ROLE>'
  STORAGE_ALLOWED_LOCATIONS = ('s3://<BUCKET>/<PREFIX>/gold_export/');
GRANT USAGE ON INTEGRATION GRIL_S3_INT TO ROLE GRIL_TRANSFORMER;

USE ROLE GRIL_TRANSFORMER;
USE SCHEMA GRIL.RAW;

CREATE FILE FORMAT IF NOT EXISTS PARQUET_FF TYPE = PARQUET;

CREATE STAGE IF NOT EXISTS GOLD_EXPORT_STAGE
  URL = 's3://<BUCKET>/<PREFIX>/gold_export/'
  STORAGE_INTEGRATION = GRIL_S3_INT
  FILE_FORMAT = (FORMAT_NAME = 'GRIL.RAW.PARQUET_FF');
