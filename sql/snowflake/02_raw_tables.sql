USE ROLE GRIL_TRANSFORMER;
USE SCHEMA GRIL.RAW;

CREATE TABLE IF NOT EXISTS DIM_COUNTRY (
  COUNTRY_KEY         NUMBER(38,0),
  COUNTRY_ISO3        VARCHAR,
  COUNTRY_ISO2        VARCHAR,
  COUNTRY_NAME        VARCHAR,
  REGION_NAME         VARCHAR,
  INCOME_LEVEL_NAME   VARCHAR,
  LENDING_TYPE        VARCHAR,
  CAPITAL_CITY        VARCHAR,
  LONGITUDE           FLOAT,
  LATITUDE            FLOAT,
  _LOADED_AT          TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS DIM_INDICATOR (
  INDICATOR_KEY       NUMBER(38,0),
  INDICATOR_CODE      VARCHAR,
  INDICATOR_NAME      VARCHAR,
  SOURCE_SYSTEM       VARCHAR,
  DOMAIN              VARCHAR,
  DIRECTION           VARCHAR,
  _LOADED_AT          TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS FACT_INDICATOR_OBSERVATION (
  COUNTRY_KEY         NUMBER(38,0),
  INDICATOR_KEY       NUMBER(38,0),
  YEAR                NUMBER(4,0),
  VALUE               FLOAT,
  _LOADED_AT          TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS FACT_COUNTRY_RISK_SCORE (
  COUNTRY_KEY            NUMBER(38,0),
  YEAR                   NUMBER(4,0),
  HEALTH_RISK_SCORE      FLOAT,
  FINANCIAL_RISK_SCORE   FLOAT,
  COMPOSITE_RISK_SCORE   FLOAT,
  RISK_TIER              VARCHAR,
  N_INDICATORS           NUMBER(10,0),
  _LOADED_AT             TIMESTAMP_NTZ
);
